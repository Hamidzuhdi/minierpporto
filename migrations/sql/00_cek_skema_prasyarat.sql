    UNION ALL SELECT 'payments'
    UNION ALL SELECT 'purchase_items'
    UNION ALL SELECT 'purchases'
    UNION ALL SELECT 'service_prices'
    UNION ALL SELECT 'spareparts'
    UNION ALL SELECT 'spk'
    UNION ALL SELECT 'spk_discount_histories'
    UNION ALL SELECT 'spk_estimate_pdf_batches'
    UNION ALL SELECT 'spk_items'
    UNION ALL SELECT 'spk_services'
    UNION ALL SELECT 'users'
    UNION ALL SELECT 'vehicles'
    UNION ALL SELECT 'warehouse_out'
) e
LEFT JOIN information_schema.TABLES t
       ON t.TABLE_SCHEMA = DATABASE() AND t.TABLE_NAME = e.tabel
WHERE t.TABLE_NAME IS NULL
ORDER BY e.tabel;

