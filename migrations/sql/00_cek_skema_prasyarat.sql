FROM (
    SELECT 'audit_logs' AS tabel
    UNION ALL SELECT 'customers'
    UNION ALL SELECT 'expense_categories'
    UNION ALL SELECT 'finance_accounts'
    UNION ALL SELECT 'finance_transactions'
    UNION ALL SELECT 'invoices'
